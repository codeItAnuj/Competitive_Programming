#include<bits/stdc++.h>
using namespace std;
typedef long long ll;

void helper(){
    ll n,x;
    cin>>n>>x;
    vector<ll>v(n+1);
    ll sum=0,min=0,max=0;
    for(ll i=1;i<=n;i++){
        cin>>v[i];
        sum+=v[i];
        max+=ceil(v[i]/(x*1.0));
    }
    min=ceil(sum/(x*1.0));
    cout<<min<<' '<<max<<'\n';
    return;
}

