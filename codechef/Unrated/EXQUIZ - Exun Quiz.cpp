#include<bits/stdc++.h>
using namespace std;
typedef long long ll;

void helper(){
    ll n,s;
    cin>>n>>s;
    ll ans=ceil(s/4.0);
    ll temp=s%4;
    if(temp>0){
        ans+=(4-temp);
    }
    if(ans<=n){
        cout<<ans<<'\n';
        return;
    }
    cout<<-1<<'\n';
}

